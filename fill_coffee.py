def fill_card(card_id):
    """填充单张咖啡卡"""
    card_path = os.path.join(CARDS_DIR, f"{card_id}.html")
    if not os.path.exists(card_path):
        print(f"[跳过] 未找到: {card_path}")
        return False
    
    recipe = COFFEE_RECIPES.get(card_id)
    if not recipe:
        print(f"[跳过] 无配方: {card_id}")
        return False
    
    with open(card_path, encoding='utf-8') as f:
        content = f.read()
    
    # 备份
    backup_path = card_path + '.bak'
    if not os.path.exists(backup_path):
        shutil.copy2(card_path, backup_path)
    
    # 生成付费区内容
    ing_lines = []
    for name, qty, note in recipe['ingredients']:
        ing_lines.append(f'  ✅ <strong>{name}</strong>：{qty}（{note}）')
    ing_html = '<br>\n'.join(ing_lines)
    
    process_html = ''
    for i, step in enumerate(recipe['process'], 1):
        process_html += f'    <li>{step}</li>\n'
    
    paid_html = f'''<div class="desc">
  <strong>完整配方</strong><br>
{ing_html}
  <br>
  <strong>工艺步骤</strong>
  <ol>
{process_html}
  </ol>
  <strong>成本拆分</strong><br>
  {recipe['cost_breakdown']}<br><br>
  <strong>交付内容：</strong><br>
  ✅ 精确到ml/g的商用配比（含多规格换算表）<br>
  ✅ 完整操作标准（温度/时间/手法全参数）<br>
  ✅ 原料选品方案（品牌对比+采购渠道推荐）<br>
  ✅ 设备清单+选购指南<br>
  ✅ 常见翻车解法+出餐效率优化
</div>
  <a class="btn" href="https://foodintelai.com">加微信 canglin1985 获取</a>'''
    
    # 替换paywall里的内容
    old_pattern = r'(<div class="paywall">\s*<div class="price">)(¥\d+)(</div>)(.*?)(</div>\s*</div>)'
    import re
    
    m = re.search(r'(<div class="paywall">.*?)(<div class="desc">)(.*?)(</div>\s*<a class="btn")(.*?)(</div>\s*</div>)', content, re.DOTALL)
    
    if m:
        # 保留price和price后面的部分，替换desc区域
        prefix = m.group(1)
        # 找到price的结束位置
        price_end = content.find('</div>', content.find('class="price"')) + 6
        after_price = content[price_end:]
        
        # 找到desc的起始和结束
        desc_start = after_price.find('<div class="desc">')
        desc_end = after_price.find('</div>', desc_start) + 6
        
        # 重建
        new_section = after_price[:desc_start] + paid_html + after_price[desc_end:]
        
        full_prefix = content[:price_end]
        new_content = full_prefix + new_section
        
        with open(card_path, 'w', encoding='utf-8') as f:
            f.write(new_content)
        print(f"[成功] {card_id} {recipe['name']}")
        return True
    else:
        # 另外一种结构——直接替换desc标签对之间的内容
        m2 = re.search(r'(<div class="desc">)(.*?)(</div>)', content, re.DOTALL)
        if m2:
            new_content = content.replace(m2.group(0), paid_html)
            with open(card_path, 'w', encoding='utf-8') as f:
                f.write(new_content)
            print(f"[成功] {card_id} {recipe['name']} (模式2)")
            return True
        else:
            print(f"[失败] 无法找到desc标签: {card_id}")
            return False

def main():
    success = 0
    for cid in ['CF-01','CF-02','CF-03','CF-04','CF-05','CF-06','CF-07','CF-08']:
        if fill_card(cid):
            success += 1
    print(f"\n处理完成: {success}/8 张")

if __name__ == '__main__':
    main()
